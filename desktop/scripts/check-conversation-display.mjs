import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';

const source=await readFile(new URL('../src/lib/conversationDisplay.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {foldIntermediateMessages}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const messages=[{id:'u1',role:'user',text:'Do it'},{id:'a1',createdAt:1234,role:'assistant',text:'First step'},{id:'a2',role:'assistant',text:'Second step'},{id:'a3',role:'assistant',text:'Done',edits:[{path:'a',kind:'update'}]},{id:'u2',role:'user',text:'Thanks'}];
const display=foldIntermediateMessages(messages);
assert.equal(display.length,3);
assert.equal(display[1].text,'Done');
assert.deepEqual(display[1].steps.map(step=>step.text),['First step','Second step']);
assert.equal(display[1].edits.length,1);
assert.equal(display[1].steps[0].createdAt,1234);
assert.deepEqual(foldIntermediateMessages([{id:'single',role:'assistant',text:'Only answer'}]),[{id:'single',role:'assistant',text:'Only answer'}]);
console.log('Consecutive assistant updates fold under their final response');
const {authoredPromptText,checkpointMessages}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const original={id:'typed',role:'user',text:'Review this project'};
const issue='\nProject feedback tools: when CERBERUS_ISSUE_TOOL is set, internal helper context. Report the issue URL after a confirmed write.\n';
const mail='\nEmail tools (only when CERBERUS_EMAIL_TOOL is set): helper context. The mail provider and your agent provider may retain accessed content.\n';
assert.equal(authoredPromptText(original.text+issue,[original]),original.text);
assert.equal(authoredPromptText(original.text+mail+issue,[original]),original.text);
assert.equal(authoredPromptText(original.text+issue+'A real additional request',[original]),original.text+issue+'A real additional request');
assert.equal(authoredPromptText(issue,[{...original,text:issue}]),issue,'Authored instructions must not be hidden');
assert.equal(authoredPromptText(original.text+issue,[]),original.text+issue,'Do not guess another user prompt');
const active=[{id:'a',role:'assistant',text:'',steps:[{kind:'command',text:'private command output'},{kind:'commentary',text:'Checkpoint: tests passed'}],edits:[{path:'file'}]}];
const checkpoints=checkpointMessages(active);
assert.equal(checkpoints[0].text,'Checkpoint: tests passed');assert.equal(checkpoints[0].steps,undefined);assert.equal(checkpoints[0].edits,undefined);
assert.equal(active[0].steps.length,2,'Presentation must preserve the stored trace');
assert.equal(checkpointMessages([{...active[0],text:'Final response'}])[0].text,'Final response');
console.log('Authored prompt restoration and checkpoint-only live presentation preserve raw history');
