import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../src/lib/ciAccessNotice.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {ciAccessNotice}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const raw='GitHub credential storage is unavailable: Platform secure storage failure: DBus error: Did not receive a reply';
const notice=ciAccessNotice(['Cerberus','1100','InDEx','CI'].map(repository=>({repository,message:raw})));
assert.match(notice.message,/Cerberus, 1100, InDEx, CI/);
assert.ok(!notice.message.includes('DBus error'));
assert.equal(notice.steps.length,3);
assert.ok(notice.steps.some(step=>step.includes('already unlocked')));
assert.ok(notice.steps.some(step=>step.includes('only if')));
assert.equal(notice.links.length,2);
assert.match(notice.details,/DBus error/);
const mixed=ciAccessNotice([{repository:'Cerberus',message:raw},{repository:'Other',message:'Permission denied'}]);
assert.match(mixed.message,/Other: Permission denied/);
assert.equal(ciAccessNotice([{repository:'Other',message:'Reconnect GitHub'}]).steps,undefined);
console.log('CI access notice grouping, recovery guidance, mixed errors and diagnostics passed');
