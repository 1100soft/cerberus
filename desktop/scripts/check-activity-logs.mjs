import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const load=async(file,replace=source=>source)=>{
 const source=replace(await readFile(new URL('../src/lib/'+file,import.meta.url),'utf8'));
 const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
 return import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
};
const {activityTime}=await load('activityTime.ts');
const now=new Date(2026,9,23,14,30).getTime();
assert.equal(activityTime(now,now),'Now');
assert.equal(activityTime(now+1000,now),'Now');
assert.equal(activityTime(now-59000,now),'Now');
assert.match(activityTime(now-60000,now),/^\d\d:\d\d$/);
assert.match(activityTime(now-86399000,now),/^\d\d:\d\d$/);
assert.doesNotMatch(activityTime(now-86400000,now),/:/);
assert.ok(activityTime(new Date(2025,9,23).getTime(),now).includes('2025'));
assert.equal(activityTime(NaN,now),'—');
globalThis.window=globalThis;
globalThis.saved=[];
const logs=await load('automationLogs.ts',source=>source.replace("import { api, type AutomationLog } from './api';","const api={writeAutomationLog:async(entry:any)=>{globalThis.saved.push(entry)},deleteAutomationLog:async()=>{}};\ntype AutomationLog=any;"));
const entry={automationId:'job',repositoryId:'repo',runId:'run',createdAt:now,kind:'shell',status:'running',command:'printf test',stdout:'',stderr:'',response:'',activity:''};
await logs.beginAutomationLog(entry);
logs.updateAutomationLog(entry,{stdout:'one\n'});
logs.updateAutomationLog(entry,{stdout:'one\ntwo\n'});
logs.updateAutomationLog(entry,{stdout:'one\ntwo\n',stderr:'warning'});
await logs.finishAutomationLog({...entry,status:'completed',stdout:'one\ntwo\n',stderr:'warning'});
const result=logs.currentAutomationLogs('job')[0];
assert.deepEqual(result.events.filter(event=>event.stream==='stdout').map(event=>event.text),['one\n','two\n']);
assert.equal(result.events.filter(event=>event.stream==='stderr').length,1);
assert.equal(result.events.at(-1).text,'completed');
assert.ok(result.events.every(event=>Number.isFinite(event.at)&&event.at>0));
assert.deepEqual(globalThis.saved.at(-1).events,result.events);
console.log('Compact timestamp boundaries and persisted incremental log events passed');
