import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../src/lib/automationMaintenance.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {startAutomationMaintenance}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
let finishRecovery;let sweeps=0;const errors=[];
const pending=startAutomationMaintenance(()=>new Promise(resolve=>{finishRecovery=resolve;}),async()=>{sweeps++;},error=>errors.push(error));
await new Promise(resolve=>setImmediate(resolve));
assert.equal(sweeps,1,'Delayed recovery blocked overdue cleanup');
finishRecovery();await pending;assert.equal(sweeps,2,'Recovered protection state was not rechecked');
sweeps=0;
await startAutomationMaintenance(async()=>{throw Error('recovery unavailable');},async()=>{sweeps++;},error=>errors.push(error));
assert.equal(sweeps,2,'Recovery failure prevented cleanup');
assert.equal(errors.length,1);
let attempts=0;
await startAutomationMaintenance(async()=>{},async()=>{if(++attempts===1)throw Error('cleanup failed');},error=>errors.push(error));
assert.equal(attempts,2,'Initial sweep failure prevented post-recovery retry');
console.log('Automation maintenance: delayed/failed recovery and cleanup retry passed');
