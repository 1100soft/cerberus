import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const data=new Map();let writes=0;
globalThis.localStorage={getItem:key=>data.get(key)||null,setItem:(key,value)=>{data.set(key,value);if(key==='gitcerberus.agentChats')writes++;}};
globalThis.window=Object.assign(new EventTarget(),{setTimeout,clearTimeout,requestIdleCallback:callback=>setTimeout(callback,1),cancelIdleCallback:clearTimeout});
const source=(await readFile(new URL('../src/lib/agentChats.ts',import.meta.url),'utf8')).replace(/^import .*;\r?\n/gm,'');
const compiled=ts.transpileModule('const api={};\n'+source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {restoreAgentConversation,updateAgentChat}=await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
restoreAgentConversation({id:'stream',repositoryId:'project',profile:{id:'provider',provider:'codex'},name:'Stream',messages:[{role:'assistant',text:'start'}],running:true,status:'Working',activity:'',updatedAt:Date.now()});
for(let i=0;i<50;i++)updateAgentChat('stream',{messages:[{role:'assistant',text:'token '+i}]});
assert.equal(writes,0,'streaming must not serialize all conversations for every token');
await new Promise(resolve=>setTimeout(resolve,650));
assert.equal(writes,1,'stream updates should share one idle backup');
assert.equal(JSON.parse(data.get('gitcerberus.agentChats'))[0].messages[0].text,'token 49');
updateAgentChat('stream',{running:false,messages:[{role:'assistant',text:'completed'}]});
assert.equal(writes,2,'completion must preserve the final recovery snapshot immediately');
assert.equal(JSON.parse(data.get('gitcerberus.agentChats'))[0].messages[0].text,'completed');
updateAgentChat('stream',{running:true,messages:[{role:'assistant',text:'last pending output'}]});
window.dispatchEvent(new Event('pagehide'));
assert.equal(JSON.parse(data.get('gitcerberus.agentChats'))[0].messages[0].text,'last pending output','exit must flush pending recovery data');
console.log('Chat persistence: streaming coalesces idle backups; completion and page exit preserve final content.');
