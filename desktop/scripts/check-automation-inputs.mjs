import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../src/lib/automationInputs.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {initialInputValues,resolveInputValues,inputDefinitionsError,inputEnvironment,scriptInputName,unifyInput,inputKey}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const definitions=[{name:'version',type:'choice',options:['major','minor','patch'],defaultValue:'patch'},{name:'count',type:'number',defaultValue:'0'},{name:'publish',type:'boolean'},{name:'notes',type:'text',required:false}];
assert.equal(inputDefinitionsError(definitions),'');
assert.deepEqual({...resolveInputValues(definitions,initialInputValues(definitions))},{version:'patch',count:0,publish:false,notes:''});
const values=resolveInputValues(definitions,{version:'minor',count:'2.5',publish:true,notes:'$(touch unsafe); "quoted"\nline'});
assert.deepEqual(inputEnvironment(values),{CERBERUS_INPUT_VERSION:'minor',CERBERUS_INPUT_COUNT:'2.5',CERBERUS_INPUT_PUBLISH:'true',CERBERUS_INPUT_NOTES:'$(touch unsafe); "quoted"\nline'});
assert.throws(()=>resolveInputValues(definitions,{version:'unknown'}));
assert.throws(()=>resolveInputValues(definitions,{count:'Infinity'}));
assert.throws(()=>resolveInputValues(definitions,{publish:'false'}));
assert.throws(()=>resolveInputValues([{name:'required',type:'text'}],{}));
assert.ok(inputDefinitionsError([{name:'a',type:'text'},{name:'A',type:'text'}]));
assert.ok(inputDefinitionsError([{name:'choice',type:'choice',options:['same','same']} ]));
assert.equal(scriptInputName('__existing_ID'), '__existing_ID');
assert.equal(scriptInputName('Version change'), 'version_change');
assert.equal(scriptInputName(' Déploiement / target '), 'deploiement_target');
assert.equal(scriptInputName('2026 release'), 'input_2026_release');
assert.match(scriptInputName('发布'), /^[A-Za-z_][A-Za-z0-9_]*$/);
assert.ok(inputDefinitionsError([{name:'Version change',type:'text'},{name:'version-change',type:'text'}]));
assert.ok(inputDefinitionsError([{name:' ',type:'text'}]));
const legacy=unifyInput({name:'version',label:'Version change',type:'text'});
assert.equal(legacy.name,'Version change');assert.equal(inputKey(legacy),'version');
assert.equal(inputDefinitionsError([{name:'bad-name',type:'text'}]),'');
assert.equal(inputEnvironment(resolveInputValues([{name:'Version change',type:'text'}],{version_change:'minor'})).CERBERUS_INPUT_VERSION_CHANGE,'minor');
console.log('Automation input defaults, validation, typed values, and environment data passed');
